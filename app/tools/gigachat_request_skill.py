"""Reusable discovery and clarification skill for Modus BI dashboard requests."""

import json


URI = "modus://skills/dashboard-request"

EDIT_RULES = """Сопоставь последнюю просьбу с конкретным существующим компонентом и его полем.
Если в отчёте несколько подходящих компонентов и пользователь не указал, какой нужен, задай вопрос. Не выбирай первый по порядку.
Для переименования нужна новая подпись. Не подставляй вместо неё исходный алиас, имя поля или подпись по своему выбору.
Сортировка, формат дат, подпись поля, заголовок компонента и расчёт KPI — разные настройки. Меняй только названные настройки.
Видимый заголовок оси графика меняй через giga_set_chart_axis, название всего графика — через giga_rename_component, алиас поля — через giga_set_field_display. Фраза «назови ось» касается самой оси.
В giga_set_field_display пропусти label, order и date_format, которые пользователь не просил менять. Не подставляй прежние или типовые значения.
Для дат «янв. 2026» — MMM YYYY, «январь 2026» — MMMM YYYY, «01.2026» — MM.YYYY, только год — YYYY.
Хронологический порядок от ранних к поздним — asc. Порядок от новых к старым — desc. Сортируй по полю даты.
Расчёт существующей карточки уточняй через giga_update_kpi. Название карточки меняй через giga_rename_component.
Не выдумывай поле, формулу или значение фильтра. Если запрос «исправь цифру», спроси, какую цифру и по каким данным считать.
Если пользователь просит «поменяй», но не назвал новое значение, спроси о нём. «Покороче» без примера оставляет выбор формата открытым. Уточняй направление и объект, если их нельзя вывести из текущего запроса и прежних ответов.
"""

INSTRUCTIONS = """Сначала проработай последнее сообщение в контексте всей задачи и текущего отчёта.
Определи, хочет человек создать отчёт, изменить его или получить ответ о данных.
Разбери цель, нужные показатели, разрезы, фильтры, период и ожидаемый результат.
Используй уже согласованные правила и фактическую схему. Название поля само по себе не доказывает смысл расчёта.
Если есть приложенная книга, выбери лист, подходящий для задачи. Как только лист понятен из запроса или ответов пользователя, передай его точное имя в sheet даже при уточнении другого условия. Если подходят несколько, оставь sheet пустым и спроси про лист.
Задай ровно один конкретный вопрос, если варианты меняют источник, бизнес-смысл показателя, зерно расчёта или состав отбираемых строк. При нескольких неизвестных уточни сначала источник. Если неясен лист, спроси только про лист, а в вариантах ответа приведи его точное название.
Дай до трёх коротких вариантов на языке пользователя. Продолжай исходное задание после ответа, даже если ответ состоит из нескольких слов.
Если источник и смысл показателей определены, оставь выбор подходящей визуализации и компоновки за моделью.
Для составного показателя выясни, есть ли уже рассчитанный итог. Обоснуй по данным, что он совпадает с составляющими, либо уточни формулу. Готовый итог нельзя складывать с его составляющими.
Указывай даты и периоды с той точностью, которая есть в данных или словах пользователя. Для месяца без года сохраняй только месяц.
Для существующей диаграммы, если пользователь указал сортировку или формат подписей, запланируй giga_set_field_display. «Восходящая» значит asc, «Янв 2026» значит MMM YYYY. Если график и поле однозначны из текущего отчёта или истории, выполняй без повторного вопроса. Алиас поля, формат его значений и привязка к источнику — разные действия.
Наблюдения по приложенному снимку — контекст к сообщению пользователя. Учитывай их при выборе компонента и правки. Если в сообщении только снимок, уточни, что на нём нужно изменить, до записи.
Пустые данные, неясный лист и неподтверждённая формула не разрешают запись спорного результата.
Формулы и поля текущего отчёта сохраняются, пока пользователь не попросит их изменить.
Верни структурированный план через dashboard_request_plan. Это служебный шаг.
"""

PLAN_FUNCTION = {
    "name": "dashboard_request_plan",
    "description": "Зафиксировать решение о способе проработки запроса перед созданием или изменением отчёта.",
    "parameters": {
        "type": "object",
        "properties": {
            "status": {"type": "string", "enum": ["ready", "clarify", "answer"]},
            "summary": {"type": "string", "description": "Краткий смысл работы и используемые поля, без догадок."},
            "question": {"type": "string", "description": "Один вопрос пользователю при status=clarify."},
            "choices": {"type": "array", "items": {"type": "string"}, "description": "Короткие варианты ответа."},
            "sheet": {"type": "string", "description": "Точное имя одного выбранного листа загружаемой книги."},
            "rules": {"type": "array", "items": {"type": "string"},
                      "description": "Явно согласованные бизнес-правила для следующего шага."},
            "edit_tool": {"type":"string", "enum":["", "giga_set_field_display", "giga_rename_component", "giga_update_kpi", "giga_select_filter"],
                          "description":"Укажи подходящий инструмент, только если запрос — одна определённая правка существующего компонента. Для нескольких независимых операций или создания оставь пустым."},
            "field_options": {"type":"array", "items":{"type":"string", "enum":["label", "order", "date_format"]},
                              "description":"При edit_tool=giga_set_field_display перечисли только явно запрошенные настройки: label — подпись, order — сортировка, date_format — вид дат."},
        },
        "required": ["status", "summary"],
    },
    "few_shot_examples": [
        {"request": "Из приложенной книги покажи итоги продаж. В книге одинаковые листы за разные месяцы.",
         "params": {"status": "clarify", "summary": "Итоги продаж за выбранный месяц", "question": "Какой лист использовать?"}},
        {"request": "Возьми лист Ноябрь и покажи сумму по полю Выручка в разрезе поля Регион.",
         "params": {"status": "ready", "summary": "Сумма Выручки по Регионам", "sheet": "Ноябрь", "rules": ["Суммировать поле Выручка"]}},
    ],
}


def register_request_skill(mcp):
    @mcp.resource(URI, mime_type="application/json")
    def dashboard_request_skill() -> str:
        """Профиль проработки коротких запросов на создание дашборда."""
        return json.dumps({
            "version": 1, "instructions": INSTRUCTIONS + "\n" + EDIT_RULES, "editing_rules": EDIT_RULES, "function": PLAN_FUNCTION,
        }, ensure_ascii=False)
